    /**
     * Recherche un étudiant par nom ou prénom
     */
    /**
     * @return Etudiant[]
     */
    public function searchByNameOrPrenom(string $query): array
    {
        return $this->createQueryBuilder('e')
            ->where('e.nom LIKE :query OR e.prenom LIKE :query OR e.matricule LIKE :query')
            ->setParameter('query', '%' . $query . '%')
            ->orderBy('e.nom', 'ASC')
            ->getQuery()
            ->getResult();
    }
